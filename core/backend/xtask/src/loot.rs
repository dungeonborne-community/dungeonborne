/// The template and where to write the tables: a season with its own seasons/<id>/loot/loot.toml — its template and seasons/<id>/balance/,
/// otherwise (no season or the season has no loot) — loot/loot.toml and balance/
struct Target {
    template: PathBuf,
    out: PathBuf,
}

fn target(season: Option<&str>) -> Target {
    if let Some(id) = season {
        let t = crate::season::dir(id).join("loot").join("loot.toml");
        if t.exists() {
            return Target { template: t, out: crate::season::balance_dir(id) };
        }
        println!("season {} has no loot/loot.toml — base loot ({})", id, TEMPLATE);
    }
    Target { template: PathBuf::from(TEMPLATE), out: PathBuf::from(BALANCE) }
}

/// Current loot table of the target: the season's if it already exists, else the base one
fn current_table(t: &Target, name: &str) -> PathBuf {
    let p = t.out.join(format!("{}.json", name));
    if p.exists() {
        p
    } else {
        Path::new(BALANCE).join(format!("{}.json", name))
    }
}
