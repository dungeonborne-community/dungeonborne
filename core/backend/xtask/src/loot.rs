/// item price for quality: system_repurchase_price, else item_quest_value; no price — not in the map
pub fn item_prices() -> HashMap<i64, f64> {
    rows_in(BALANCE, "item_type")
        .iter()
        .filter_map(|r| {
            let p = r["system_repurchase_price"].as_f64().or_else(|| r["item_quest_value"].as_f64())?;
            (p > 0.0).then(|| (r["type_id"].as_i64().unwrap_or(0), p))
        })
        .collect()
}

fn compile(s: &Schema, tg: &Target) -> Result<Compiled, Vec<String>> {
    let text = std::fs::read_to_string(&tg.template).map_err(|e| vec![format!("{}: {} — run `cargo xtask loot export` first", tg.template.display(), e)])?;
    compile_text(s, tg, &text)
}

fn compile_text(s: &Schema, tg: &Target, text: &str) -> Result<Compiled, Vec<String>> {
    let tpl = tg.template.display();
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let doc: toml::Value = toml::from_str(text).map_err(|e| vec![format!("{}: {}", tpl, e)])?;
    let doc = serde_json::to_value(doc).unwrap();
    let names = Names::load(s, BALANCE);
    let cats = item_cats();
    let resolve = |n: &str| names.item_by_name(n);
    let mut errors = Vec::new();
    let mut notes = Vec::new();
    let prices = item_prices();
    let rules = Rules::parse(&doc["rules"], "rules", &[], &mut errors);
    for k in doc.as_object().into_iter().flatten().map(|(k, _)| k) {
        if !["rules", "modes", "groups", "pools", "keep_base"].contains(&k.as_str()) {
            errors.push(format!("unknown section [{}]", k));
        }
    }
    // modes: context 0 — [rules] for all maps, 1.. — [modes.*] for their own maps (on top of [rules])
    let mut modes: Vec<Mode> = Vec::new();
    let mut mode_of_map: HashMap<i64, usize> = HashMap::new();
    for (name, v) in doc["modes"].as_object().into_iter().flatten() {
        let at = format!("modes.{}", name);
        let r = Rules::parse(v, &at, &["maps", "name"], &mut errors);
        let maps: Vec<i64> = v["maps"].as_array().into_iter().flatten().map(int).collect();
        if maps.is_empty() {
            errors.push(format!("[{}]: maps = [..] is required", at));
        }
        for &m in &maps {
            if let Some(&other) = mode_of_map.get(&m) {
                errors.push(format!("[{}]: map {} is already in mode {}", at, m, modes[other - 1].name));
            }
            mode_of_map.insert(m, modes.len() + 1);
        }
        modes.push(Mode { name: name.clone(), maps, rules: rules.with(&r) });
    }
    let ctx_rules = |ctx: usize| -> &Rules { if ctx == 0 { &rules } else { &modes[ctx - 1].rules } };

    // --- pools (context 0); for modes a pool is built by its own rules on first use ---
    let pool_defs = doc["pools"].as_object().cloned().unwrap_or_default();
    let mut used_ids: HashSet<i64> = pool_defs.keys().filter_map(|k| k.parse().ok()).collect();
    let mut next_pool = NEW_POOL_ID;
    let mut alloc_pool_id = |used_ids: &mut HashSet<i64>| {
        while used_ids.contains(&next_pool) {
            next_pool += 1;
        }
        used_ids.insert(next_pool);
        next_pool
    };
    let mut pools: Vec<Pool> = Vec::new();
    let mut pool_keys: Vec<String> = Vec::new();
    let mut pool_ctx: HashMap<(usize, String), usize> = HashMap::new();
    let mut removed = vec![0usize; modes.len() + 1];
    let mut empty_pools = 0;
    for (key, p) in &pool_defs {
        let id = key.parse::<i64>().unwrap_or_else(|_| alloc_pool_id(&mut used_ids));
        let (rows, share, rm) = build_pool(key, p, &rules, &resolve, &cats, &prices, true, &mut errors);
        removed[0] += rm;
        if rows.is_empty() {
            empty_pools += 1;
        }
        let mut extra = p.as_object().cloned().unwrap_or_default();
        extra.remove("name");
        extra.remove("items");
        pool_ctx.insert((0, key.clone()), pools.len());
        pools.push(Pool { id, rows, share, extra });
        pool_keys.push(key.clone());
    }
    let mut mode_pools = 0;

    // --- groups and slots ---
    let src_ids: HashMap<String, i64> = rows_in(BALANCE, "loot_source_map")
        .iter()
        .filter_map(|r| Some((r["name"].as_str()?.to_string(), r["id"].as_i64()?)))
        .collect();
    let groups_def = doc["groups"].as_object().cloned().unwrap_or_default();
    let mut slot_ids_reserved: HashSet<i64> = HashSet::new();
    for g in groups_def.values() {
        for sl in g["slots"].as_array().into_iter().flatten() {
            if let Some(id) = sl["id"].as_i64() {
                slot_ids_reserved.insert(id);
            }
        }
    }
    let mut next_slot = NEW_SLOT_ID;
    let mut slot_rows: Vec<Json> = Vec::new();
    let mut slot_by_id: HashMap<i64, String> = HashMap::new(); // id -> contents
    let mut slot_by_content: HashMap<String, i64> = HashMap::new();
    let mut source_rows: Vec<Json> = Vec::new();
    let mut seen_src: HashSet<(i64, i64, i64)> = HashSet::new();
    let mut groups: Vec<GroupInfo> = Vec::new();
    let (mut dropped_slots, mut renumbered) = (0, 0);
    for (gkey, g) in &groups_def {
        for k in g.as_object().into_iter().flatten().map(|(k, _)| k) {
            if !["name", "sources", "slots", "maps", "map_id", "loot_types", "loot_type", "limit"].contains(&k.as_str()) {
                errors.push(format!("groups.{}: unknown field \"{}\"", gkey, k));
            }
        }
        // maps = [..] / map_id = N (0 by default — loot for all maps); the same for loot_types / loot_type
        let list_or = |many: &str, one: &str| -> Vec<i64> {
            match g[many].as_array() {
                Some(a) if !a.is_empty() => a.iter().map(int).collect(),
                _ => vec![int(&g[one])],
            }
        };
        let (maps, types) = (list_or("maps", "map_id"), list_or("loot_types", "loot_type"));
        // sources — once per group
        let mut srcs: Vec<i64> = Vec::new();
        for (n, src) in g["sources"].as_array().into_iter().flatten().enumerate() {
            match src {
                Json::Number(_) => srcs.push(int(src)),
                Json::String(name) => match name.parse::<i64>().ok().or_else(|| src_ids.get(name).copied()) {
                    Some(id) => srcs.push(id),
                    None => errors.push(format!("groups.{} sources[{}]: \"{}\" is not in loot_source_map", gkey, n, name)),
                },
                _ => {}
            }
        }
        // group maps by contexts: 0 — without a mode, 1.. — modes
        let mut parts: Vec<(usize, Vec<i64>)> = Vec::new();
        for &m in &maps {
            let ctx = mode_of_map.get(&m).copied().unwrap_or(0);
            match parts.iter_mut().find(|p| p.0 == ctx) {
                Some(p) => p.1.push(m),
                None => parts.push((ctx, vec![m])),
            }
        }
        parts.sort_by_key(|p| p.0);
        for (ctx, part_maps) in parts {
            let crules = ctx_rules(ctx);
            let mut info = GroupInfo {
                name: g["name"].as_str().unwrap_or("").to_string(),
                view: GroupView {
                    key: if ctx == 0 { gkey.clone() } else { format!("{}@{}", gkey, modes[ctx - 1].name) },
                    group: gkey.clone(),
                    sources: 0,
                    maps: part_maps.clone(),
                    types: types.clone(),
                    slots: vec![],
                },
            };
            let mut loot_ids: Vec<i64> = Vec::new();
            for (n, sl) in g["slots"].as_array().into_iter().flatten().enumerate() {
                let at = format!("groups.{} slots[{}]", gkey, n);
                let keys: Vec<Json> = if !sl["pool"].is_null() {
                    vec![sl["pool"].clone()]
                } else {
                    sl["pools"].as_array().cloned().unwrap_or_default()
                };
                if keys.is_empty() {
                    errors.push(format!("{}: no pool / pools", at));
                    continue;
                }
                let pr: Vec<i64> = match sl["pr"].as_array() {
                    Some(a) => a.iter().map(int).collect(),
                    None if keys.len() == 1 => vec![100],
                    None => vec![1; keys.len()],
                };
                if pr.len() != keys.len() {
                    errors.push(format!("{}: pr — {} numbers, but {} pools", at, pr.len(), keys.len()));
                    continue;
                }
                let mut picked: Vec<(usize, i64)> = Vec::new();
                for (k, w) in keys.iter().zip(&pr) {
                    let ks = match k {
                        Json::String(s) => s.clone(),
                        v => v.to_string(),
                    };
                    let Some(&base) = pool_ctx.get(&(0, ks.clone())) else {
                        if ctx == 0 {
                            errors.push(format!("{}: no pool \"{}\"", at, ks));
                        }
                        continue;
                    };
                    // mode pool: build it by the mode rules; if it came out the same as the shared one — take the shared one
                    let i = match pool_ctx.get(&(ctx, ks.clone())) {
                        Some(&i) => i,
                        None => {
                            let (rows, share, rm) = build_pool(&ks, &pool_defs[&ks], crules, &resolve, &cats, &prices, false, &mut errors);
                            removed[ctx] += rm;
                            let i = if rows == pools[base].rows {
                                base
                            } else {
                                let extra = pools[base].extra.clone();
                                let id = alloc_pool_id(&mut used_ids);
                                mode_pools += 1;
                                pools.push(Pool { id, rows, share, extra });
                                pool_keys.push(ks.clone());
                                pools.len() - 1
                            };
                            pool_ctx.insert((ctx, ks.clone()), i);
                            i
                        }
                    };
                    if !pools[i].rows.is_empty() {
                        picked.push((i, *w));
                    }
                }
                if picked.is_empty() {
                    dropped_slots += 1;
                    continue;
                }
                let pr_total: f64 = picked.iter().map(|p| p.1 as f64).sum();
                let shares: Vec<(usize, f64)> = picked.iter().map(|&(i, w)| (i, w as f64 / pr_total)).collect();
                let cmult: f64 = shares.iter().map(|&(i, sh)| sh * pools[i].share.iter().map(|&(c, f)| f * mult(&crules.chance, c)).sum::<f64>()).sum();
                let Some(chance) = sl["chance"].as_f64() else {
                    errors.push(format!("{}: no chance", at));
                    continue;
                };
                let rate = ((chance * 100.0 * cmult).round() as i64).min(RATE_MAX);
                let max = sl["max"].as_f64().map(|m| ((m * 100.0 * cmult).round() as i64).min(RATE_MAX)).unwrap_or(rate);
                if rate <= 0 {
                    dropped_slots += 1;
                    continue;
                }
                let mut row = json!({
                    "loot_id": 0,
                    "random_ids": picked.iter().map(|&(i, _)| pools[i].id).collect::<Vec<_>>(),
                    "pr": picked.iter().map(|&(_, w)| w).collect::<Vec<_>>(),
                });
                for (k, v) in sl.as_object().into_iter().flatten() {
                    match k.as_str() {
                        "id" | "pool" | "pools" | "pr" | "chance" | "max" => {}
                        _ => {
                            row[k] = v.clone(); // condition, rare_pool… — as is (the schema will check)
                        }
                    }
                }
                row["default_rate"] = json!(rate);
                row["max_rate"] = json!(max);
                let content = row.to_string();
                // id from the template — only for maps without a mode; mode slots get new ids
                let lid = match sl["id"].as_i64().filter(|_| ctx == 0) {
                    Some(id) if slot_by_id.get(&id).map(|c| c == &content).unwrap_or(true) => id,
                    want => {
                        if want.is_some() && ctx == 0 {
                            renumbered += 1;
                        }
                        match slot_by_content.get(&content) {
                            Some(&id) => id,
                            None => {
                                while slot_ids_reserved.contains(&next_slot) || slot_by_id.contains_key(&next_slot) {
                                    next_slot += 1;
                                }
                                next_slot
                            }
                        }
                    }
                };
                if !slot_by_id.contains_key(&lid) {
                    slot_by_id.insert(lid, content.clone());
                    slot_by_content.entry(content).or_insert(lid);
                    row["loot_id"] = json!(lid);
                    slot_rows.push(row);
                }
                loot_ids.push(lid);
                info.view.slots.push(SlotView { n, rate, pools: shares });
            }
            for &id in &srcs {
                info.view.sources += 1;
                // a row per pair (map, loot_type)
                for &map_id in &part_maps {
                    for &loot_type in &types {
                        if !seen_src.insert((id, map_id, loot_type)) {
                            errors.push(format!("groups.{}: source {} (map {}, type {}) is already in another group", gkey, id, map_id, loot_type));
                            continue;
                        }
                        let mut row = json!({ "ue_loot_source_id": id, "map_id": map_id, "loot_type": loot_type, "loot_ids": loot_ids });
                        if int(&g["limit"]) != 0 {
                            row["limit"] = g["limit"].clone();
                        }
                        source_rows.push(row);
                    }
                }
            }
            groups.push(info);
        }
    }

    let mut loot_rows = Vec::new();
    let mut rate_rows = Vec::new();
    for p in &pools {
        for &(item, cnt, level, w) in &p.rows {
            loot_rows.push(json!({ "random_id": p.id, "item_id": item, "cnt": cnt, "level": level, "rate": w }));
        }
        let mut r = Map::new();
        r.insert("random_id".into(), json!(p.id));
        r.extend(p.extra.clone());
        rate_rows.push(Json::Object(r));
    }

    if removed[0] > 0 {
        notes.push(format!("[rules] items removed from pools: {}", removed[0]));
    }
    for (i, m) in modes.iter().enumerate() {
        notes.push(format!(
            "[modes.{}] maps {:?}: items removed {}, quality {}",
            m.name, m.maps, removed[i + 1], m.rules.quality
        ));
    }
    if mode_pools > 0 {
        notes.push(format!("pools built separately for modes: {}", mode_pools));
    }
    if empty_pools > 0 {
        notes.push(format!("empty pools: {} (slots with them do not drop)", empty_pools));
    }
    if dropped_slots > 0 {
        notes.push(format!("slots without items or with chance 0 — removed: {}", dropped_slots));
    }
    if renumbered > 0 {
        notes.push(format!("slots with the same id but other contents — got a new id: {}", renumbered));
    }
    let mapped: HashSet<i64> = src_ids.values().copied().collect();
    let covered: HashSet<i64> = seen_src.iter().map(|x| x.0).collect();
    let uncovered = mapped.difference(&covered).count();
    if uncovered > 0 {
        notes.push(format!("sources from loot_source_map without loot in the template: {} (as before — they have no row in the table)", uncovered));
    }

    // [keep_base] maps = [..] (05.11): these maps get the base loot (balance\), not the template's. Needed by seasons: the arenas
    // of custom games (30101…30302) have no rows of their own, their chests take the loot of map 0 — and the season rewrites it
    // (Dead Money: season equipment in arena chests). Sources of map 0 of the base are copied onto these maps + the base
    // slots (loot_choose_group_rate) and pools (loot, loot_rate) they refer to.
    let keep_maps: Vec<i64> = doc["keep_base"]["maps"].as_array().into_iter().flatten().map(int).collect();
    if !keep_maps.is_empty() {
        let have_src: HashSet<String> =
            source_rows.iter().map(|r| format!("{}|{}|{}", int(&r["ue_loot_source_id"]), int(&r["map_id"]), int(&r["loot_type"]))).collect();
        let mut need_slots: HashSet<i64> = HashSet::new();
        let mut added_src = 0;
        for r in rows_in(BALANCE, "loot_ue_source_choose_group").into_iter().filter(|r| int(&r["map_id"]) == 0) {
            for &m in &keep_maps {
                let mut c = r.clone();
                c["map_id"] = Json::from(m);
                let k = format!("{}|{}|{}", int(&c["ue_loot_source_id"]), m, int(&c["loot_type"]));
                if have_src.contains(&k) {
                    continue; // the template set this map itself
                }
                need_slots.extend(c["loot_ids"].as_array().into_iter().flatten().map(int));
                source_rows.push(c);
                added_src += 1;
            }
        }
        let have_slots: HashSet<i64> = slot_rows.iter().map(|r| int(&r["loot_id"])).collect();
        let mut need_pools: HashSet<i64> = HashSet::new();
        for r in rows_in(BALANCE, "loot_choose_group_rate") {
            let id = int(&r["loot_id"]);
            if need_slots.contains(&id) && !have_slots.contains(&id) {
                need_pools.extend(r["random_ids"].as_array().into_iter().flatten().map(int));
                slot_rows.push(r);
            }
        }
        let have_pools: HashSet<i64> = loot_rows.iter().map(|r| int(&r["random_id"])).collect();
        let base_loot: Vec<Json> = rows_in(BALANCE, "loot").into_iter().filter(|r| need_pools.contains(&int(&r["random_id"]))).collect();
        let pools_added: HashSet<i64> = base_loot.iter().map(|r| int(&r["random_id"])).filter(|id| !have_pools.contains(id)).collect();
        loot_rows.extend(base_loot.into_iter().filter(|r| pools_added.contains(&int(&r["random_id"]))));
        let have_rates: HashSet<i64> = rate_rows.iter().map(|r| int(&r["random_id"])).collect();
        rate_rows.extend(
            rows_in(BALANCE, "loot_rate").into_iter().filter(|r| pools_added.contains(&int(&r["random_id"])) && !have_rates.contains(&int(&r["random_id"]))),
        );
        notes.push(format!(
            "[keep_base] maps {:?} — base loot: sources {}, slots {}, pools {}",
            keep_maps,
            added_src,
            need_slots.len(),
            pools_added.len()
        ));
    }

    // canonicalization by schema (field order, default values) and row order as in the current tables
    let mut out_tables = Vec::new();
    for (name, rows) in [("loot", loot_rows), ("loot_rate", rate_rows), ("loot_choose_group_rate", slot_rows), ("loot_ue_source_choose_group", source_rows)] {
        let cur_path = current_table(tg, name);
        let cur = tables::read_json(&cur_path).map_err(|e| vec![format!("{}: {}", cur_path.display(), e)])?;
        let desc = s.row_type(cur["type"].as_str().unwrap_or("")).ok_or(vec![format!("{}: row type not found", name)])?;
        let mut canon = Vec::new();
        for r in rows {
            match tables::row_from_json(&desc, &r) {
                Ok(m) => canon.push(tables::to_json(&m)),
                Err(e) => errors.push(format!("{}: {} ({})", name, e, r)),
            }
        }
        // row key; for a source — (source, map, loot_type)
        let key = |r: &Json| -> String {
            match name {
                "loot" | "loot_rate" => r["random_id"].to_string(),
                "loot_choose_group_rate" => r["loot_id"].to_string(),
                _ => format!("{}|{}|{}", int(&r["ue_loot_source_id"]), int(&r["map_id"]), int(&r["loot_type"])),
            }
        };
        let mut pos: HashMap<String, usize> = HashMap::new();
        for (i, r) in cur["rows"].as_array().into_iter().flatten().enumerate() {
            pos.entry(key(r)).or_insert(i);
        }
        // new source rows — by (map, loot_type, source), the rest — in template order
        let mut idx: Vec<(usize, (i64, i64, i64), usize)> = canon
            .iter()
            .enumerate()
            .map(|(i, r)| {
                let p = *pos.get(&key(r)).unwrap_or(&usize::MAX);
                let sec = if p == usize::MAX && name == "loot_ue_source_choose_group" {
                    (int(&r["map_id"]), int(&r["loot_type"]), int(&r["ue_loot_source_id"]))
                } else {
                    (0, 0, 0)
                };
                (p, sec, i)
            })
            .collect();
        idx.sort();
        let idx: Vec<(usize, usize)> = idx.into_iter().map(|(p, _, i)| (p, i)).collect();
        out_tables.push((name, idx.into_iter().map(|(_, i)| canon[i].clone()).collect()));
    }
    if errors.is_empty() {
        Ok(Compiled { tables: out_tables, pools, pool_keys, groups, notes })
    } else {
        Err(errors)
    }
}

fn print_errors(tg: &Target, errors: &[String]) {
    println!("ERRORS in {} ({}), tables not changed:", tg.template.display(), errors.len());
    errors.iter().take(40).for_each(|e| println!("  {}", e));
}

impl Compiled {
    /// What was built, in the form of the app's calculation: for the summary and the cross-check
    fn view(&self) -> DropView {
        DropView {
            pools: self.pools.iter().zip(&self.pool_keys).map(|(p, k)| PoolView { key: k.clone(), rows: p.rows.clone() }).collect(),
            groups: self.groups.iter().map(|g| g.view.clone()).collect(),
        }
    }
}

/// Average loot from one source of a group: how many items of each category and how much gold.
/// map — only groups whose maps contain this map
fn print_summary(c: &Compiled, map: Option<i64>) {
    let view = c.view();
    let cats = item_cats();
    for g in c.groups.iter().filter(|g| g.view.sources > 0 && map.map(|m| g.view.maps.contains(&m)).unwrap_or(true)) {
        let s = group_summary(&view, &g.view, &cats);
        let parts: Vec<String> = s
            .by_cat
            .iter()
            .filter(|x| x.1 >= 0.005)
            .map(|(cat, f)| if *cat == Cat::Gold { format!("{} {:.2} (≈{:.0} pcs)", cat_ru(*cat), f, s.gold) } else { format!("{} {:.2}", cat_ru(*cat), f) })
            .collect();
        let types = if g.view.types == [0] { String::new() } else { format!(" type {:?}", g.view.types) };
        println!(
            "  {:<5} {:<60} {:>3} src.{} | {:.2} items: {}",
            g.view.key,
            g.name.chars().take(60).collect::<String>(),
            g.view.sources,
            types,
            s.items,
            parts.join(", ")
        );
    }
}

pub fn show(season: Option<&str>, map: Option<i64>) -> bool {
    let s = Schema::load();
    let tg = target(season);
    match compile(&s, &tg) {
        Ok(c) => {
            c.notes.iter().for_each(|n| println!("  {}", n));
            println!("on average from one source (chest/monster), with [rules] applied{}:", map.map(|m| format!(", map {}", map_label(m))).unwrap_or_default());
            print_summary(&c, map);
            true
        }
        Err(e) => {
            print_errors(&tg, &e);
            false
        }
    }
}

pub fn build(season: Option<&str>) -> bool {
    let s = Schema::load();
    let tg = target(season);
    println!("template {} -> {}", tg.template.display(), tg.out.display());
    let c = match compile(&s, &tg) {
        Ok(c) => c,
        Err(e) => {
            print_errors(&tg, &e);
            return false;
        }
    };
    c.notes.iter().for_each(|n| println!("  {}", n));
    for (name, rows) in &c.tables {
        let path = tg.out.join(format!("{}.json", name));
        let mut cur = tables::read_json(&current_table(&tg, name)).unwrap();
        let same = cur["rows"].as_array().map(|a| a == rows).unwrap_or(false);
        println!("  {:<30} {:>6} rows {}", name, rows.len(), if same { "(unchanged)" } else { "— updated" });
        if !same || !path.exists() {
            cur["rows"] = Json::Array(rows.clone());
            std::fs::create_dir_all(&tg.out).unwrap();
            tables::write_json(&path, &cur);
        }
    }
    if c.groups.len() <= 60 {
        println!("on average from one source:");
        print_summary(&c, None);
    } else {
        println!("{} groups; average loot — cargo xtask loot show [--map=10103]", c.groups.len());
    }
    true
}

/// The target template as JSON: for the kit and the patch
pub fn read_template(season: Option<&str>) -> Result<(PathBuf, Json), String> {
    let tg = target(season);
    let text = std::fs::read_to_string(&tg.template).map_err(|e| format!("{}: {}", tg.template.display(), e))?;
    let text = text.strip_prefix('\u{feff}').unwrap_or(&text);
    let doc: toml::Value = toml::from_str(text).map_err(|e| format!("{}: {}", tg.template.display(), e))?;
    Ok((tg.template, serde_json::to_value(doc).map_err(|e| e.to_string())?))
}

/// Summary of one group for the cross-check: the same text — the same drop
fn summary_line(v: &DropView, g: &GroupView, cats: &HashMap<i64, Cat>) -> String {
    let s = group_summary(v, g, cats);
    let mut by: Vec<String> = s.by_cat.iter().map(|(c, f)| format!("{} {:.6}", cat_code(*c), f)).collect();
    by.sort();
    format!("{} {} {:?} {:?} {:.6} {:.6} {}", g.key, g.sources, g.maps, g.types, s.items, s.gold, by.join(" "))
}

/// The app's calculation (balance-kit, drop_view) vs the table build (compile): all groups of all maps, the chance of each slot,
/// each row of each pool. A mismatch means the app will show something other than what the game gets.
/// With a patch: the app computes the edits on top of the template in memory, the server edits the template text and builds the tables,
/// and the results must match.
pub fn verify_view(season: Option<&str>, patch: Option<&str>) -> bool {
    let s = Schema::load();
    let tg = target(season);
    let (path, mut doc) = match read_template(season) {
        Ok(x) => x,
        Err(e) => {
            eprintln!("{}", e);
            return false;
        }
    };
    let compiled = match patch {
        None => compile(&s, &tg),
        Some(file) => {
            let parsed = tables::read_json(Path::new(file)).map_err(|e| vec![e]).and_then(|p| balance_kit::Patch::from_json(&p).map_err(|e| vec![e.to_string()]));
            let parsed = match parsed {
                Ok(p) => p,
                Err(e) => {
                    print_errors(&tg, &e);
                    return false;
                }
            };
            let tables_now = template_data(&doc);
            for c in parsed.changes.iter().filter(|c| balance_kit::loot::is_template_table(&c.table)) {
                let ids = crate::loot_edit::row_ids(&tables_now[&c.table]);
                let place = c.row.and_then(|r| ids.get(&r)).and_then(|(key, n)| balance_kit::loot::locate(&c.table, key, *n, &c.path));
                if !place.is_some_and(|p| balance_kit::loot::apply_to_doc(&mut doc, &p, &c.new)) {
                    println!("  DIFFERENCE {} {:?} {}: the edit did not land on the template", c.table, c.row, c.path);
                    return false;
                }
            }
            crate::loot_edit::apply(&path, &parsed.changes, &tables_now).and_then(|(text, _)| compile_text(&s, &tg, &text))
        }
    };
    let compiled = match compiled {
        Ok(c) => c,
        Err(e) => {
            print_errors(&tg, &e);
            return false;
        }
    };
    let (cats, prices) = (item_cats(), item_prices());
    let ours = balance_kit::loot::drop_view(&doc, &cats, &prices);
    let theirs = compiled.view();
    let mut bad = Vec::new();
    if ours.groups.len() != theirs.groups.len() {
        bad.push(format!("groups {} and {}", ours.groups.len(), theirs.groups.len()));
    }
    let mut maps: Vec<i64> = theirs.groups.iter().flat_map(|g| g.maps.iter().copied()).collect();
    maps.sort();
    maps.dedup();
    let mut slots = 0;
    for (a, b) in ours.groups.iter().zip(&theirs.groups) {
        let (x, y) = (summary_line(&ours, a, &cats), summary_line(&theirs, b, &cats));
        if x != y {
            bad.push(format!("summary\n    app  {}\n    game {}", x, y));
        }
        if a.slots.len() != b.slots.len() {
            bad.push(format!("{}: slots {} and {}", a.key, a.slots.len(), b.slots.len()));
            continue;
        }
        for (sa, sb) in a.slots.iter().zip(&b.slots) {
            slots += 1;
            let rows = |v: &DropView, sl: &SlotView| -> Vec<(String, Vec<(i64, i64, i64, i64)>, String)> {
                sl.pools.iter().map(|&(i, sh)| (v.pools[i].key.clone(), v.pools[i].rows.clone(), format!("{:.9}", sh))).collect()
            };
            if sa.n != sb.n || sa.rate != sb.rate || rows(&ours, sa) != rows(&theirs, sb) {
                bad.push(format!("{} slot {}: chance {} and {}, pools {:?}", a.key, sa.n, sa.rate, sb.rate, sa.pools));
            }
        }
    }
    bad.iter().take(20).for_each(|b| println!("  DIFFERENCE {}", b));
    println!("cross-check {}: groups {}, slots {}, pools {}, maps {}: {}", tg.template.display(), theirs.groups.len(), slots, theirs.pools.len(), maps.len(), if bad.is_empty() { "match".to_string() } else { format!("{} mismatches", bad.len()) });
    bad.is_empty()
}

