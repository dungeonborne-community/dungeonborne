/// a source group on export
struct EGroup {
    loot_ids: Vec<i64>,
    limit: i64,
    maps: Vec<i64>,
    types: Vec<i64>,
    srcs: Vec<i64>,
}

/// label of loot_map_id (map_detail): location + difficulty (Russian: written into the template's group names)
fn map_label(m: i64) -> String {
    match m {
        0 => "по умолчанию".into(),
        10101 => "Склеп".into(),
        10102 => "Склеп Classic".into(),
        10103 => "Склеп Hard".into(),
        10201 => "Замок".into(),
        10202 => "Замок Classic".into(),
        10203 => "Замок Hard".into(),
        1..=99 => format!("стар. {}", m), // old ids from map_detail (1–18)
        _ => format!("карта {}", m),
    }
}

/// maps: None — maps from our map_detail and 0; Some(None) — all; Some(Some(list)) — only these
pub fn export(from: &str, force: bool, maps: Option<Option<Vec<i64>>>) -> bool {
    let out = Path::new(TEMPLATE);
    if out.exists() && !force {
        println!("{} already exists — edits in it will be lost. Repeat with --force", TEMPLATE);
        return false;
    }
    let s = Schema::load();
    let names = Names::load(&s, BALANCE);
    let cats = item_cats();
    let loot = rows_in(from, "loot");
    if loot.is_empty() {
        println!("{}\\loot.json: no rows (the folder with table JSON: balance or the output of `balance dump`)", from);
        return false;
    }
    // source names: from the same export (PVE has its own loot_source_map), else from balance
    let mut map_rows = rows_in(from, "loot_source_map");
    if map_rows.is_empty() {
        map_rows = rows_in(BALANCE, "loot_source_map");
    }
    let mut src_name: HashMap<i64, String> = HashMap::new();
    for r in &map_rows {
        if let (Some(n), Some(id)) = (r["name"].as_str(), r["id"].as_i64()) {
            src_name.entry(id).or_insert_with(|| n.to_string());
        }
    }
    let item_label = |id: i64| -> String {
        let n = names.item(id).unwrap_or("?");
        match cats.get(&id) {
            Some(c) => format!("{} [{}]", n, cat_code(*c)),
            None => format!("{} [нет в item_type]", n),
        }
    };

    // pools: consecutive rows with the same item/level/weight merge into cnt = [..]
    let mut pools: Vec<(i64, Vec<Entry>)> = Vec::new();
    let mut pidx: HashMap<i64, usize> = HashMap::new();
    for r in &loot {
        let rid = int(&r["random_id"]);
        let k = *pidx.entry(rid).or_insert_with(|| {
            pools.push((rid, Vec::new()));
            pools.len() - 1
        });
        let (item, cnt, level, rate) = (int(&r["item_id"]), int(&r["cnt"]), int(&r["level"]), int(&r["rate"]));
        match pools[k].1.last_mut() {
            Some(e) if e.item == item && e.level == level && e.rate == rate => e.cnts.push(cnt),
            _ => pools[k].1.push(Entry { item, level, rate, cnts: vec![cnt] }),
        }
    }
    let mut pool_extra: HashMap<i64, Map<String, Json>> = HashMap::new();
    for r in rows_in(from, "loot_rate") {
        let mut m = r.as_object().cloned().unwrap_or_default();
        let rid = m.remove("random_id").and_then(|v| v.as_i64()).unwrap_or(0);
        pool_extra.insert(rid, m);
        if !pidx.contains_key(&rid) {
            pidx.insert(rid, pools.len());
            pools.push((rid, Vec::new())); // a pool without items in loot — a slot with it gives nothing
        }
    }
    let pool_name = |entries: &[Entry]| -> String {
        let distinct: HashSet<i64> = entries.iter().map(|e| e.item).collect();
        if entries.is_empty() {
            return "(пусто)".into();
        }
        if distinct.len() == 1 {
            let all: Vec<i64> = entries.iter().flat_map(|e| e.cnts.clone()).collect();
            return format!("{}{}", names.item(entries[0].item).unwrap_or("?"), cnt_range(&all));
        }
        let mut by: Vec<(Cat, usize)> = Vec::new();
        for e in entries {
            let c = cats.get(&e.item).copied().unwrap_or(Cat::Other);
            match by.iter_mut().find(|x| x.0 == c) {
                Some(x) => x.1 += 1,
                None => by.push((c, 1)),
            }
        }
        by.sort_by(|a, b| b.1.cmp(&a.1));
        by.iter().map(|(c, n)| format!("{} {}", cat_ru(*c), n)).collect::<Vec<_>>().join(", ")
    };
    let pool_names: HashMap<i64, String> = pools.iter().map(|(id, e)| (*id, pool_name(e))).collect();

    let slots: HashMap<i64, Json> = rows_in(from, "loot_choose_group_rate").into_iter().map(|r| (int(&r["loot_id"]), r)).collect();

    // names our client knows: a source with another name is written as a number (on build the name would not resolve)
    let our_src: HashSet<String> = rows_in(BALANCE, "loot_source_map").iter().filter_map(|r| r["name"].as_str().map(String::from)).collect();
    let all_src_rows = rows_in(from, "loot_ue_source_choose_group");
    // by default — only maps we have (map_detail.loot_map_id) and 0 (the default loot)
    let maps_filter: Option<HashSet<i64>> = match maps {
        Some(m) => m.map(|v| v.iter().copied().collect()),
        None => Some(std::iter::once(0).chain(rows_in(BALANCE, "map_detail").iter().map(|r| int(&r["loot_map_id"]))).collect()),
    };
    let used_slots: HashSet<i64> =
        all_src_rows.iter().flat_map(|r| r["loot_ids"].as_array().cloned().unwrap_or_default()).map(|v| int(&v)).collect();
    let mut skipped_maps: Vec<i64> = Vec::new();

    // groups: 1) sources with the same slots on one (map, loot_type); 2) the same groups on different
    // maps -> maps = [..]; 3) on different loot_type -> loot_types = [..]
    let mut groups: Vec<EGroup> = Vec::new();
    for r in &all_src_rows {
        let (map, ty) = (int(&r["map_id"]), int(&r["loot_type"]));
        if maps_filter.as_ref().map(|f| !f.contains(&map)).unwrap_or(false) {
            if !skipped_maps.contains(&map) {
                skipped_maps.push(map);
            }
            continue;
        }
        let loot_ids: Vec<i64> = r["loot_ids"].as_array().into_iter().flatten().map(int).collect();
        let limit = int(&r["limit"]);
        let src = int(&r["ue_loot_source_id"]);
        match groups.iter_mut().find(|g| g.loot_ids == loot_ids && g.limit == limit && g.maps == [map] && g.types == [ty]) {
            Some(g) => g.srcs.push(src),
            None => groups.push(EGroup { loot_ids, limit, maps: vec![map], types: vec![ty], srcs: vec![src] }),
        }
    }
    let merge = |groups: Vec<EGroup>, by_map: bool| -> Vec<EGroup> {
        let mut out: Vec<EGroup> = Vec::new();
        for g in groups {
            let same = |o: &EGroup| {
                o.loot_ids == g.loot_ids && o.limit == g.limit && o.srcs == g.srcs && if by_map { o.types == g.types } else { o.maps == g.maps }
            };
            match out.iter_mut().find(|o| same(o)) {
                Some(o) if by_map => o.maps.extend(g.maps),
                Some(o) => o.types.extend(g.types),
                None => out.push(g),
            }
        }
        out
    };
    let mut groups = merge(merge(groups, true), false);
    for g in &mut groups {
        g.maps.sort();
        g.maps.dedup();
        g.types.sort();
        g.types.dedup();
    }
    groups.sort_by_key(|g| (g.maps.len() == 1, g.maps[0], g.types[0])); // groups shared by all maps go first

    // slots no source refers to (tutorial etc. — the game may call them by id directly):
    // a separate group without sources, so that build keeps them
    let mut unused: Vec<i64> =
        rows_in(from, "loot_choose_group_rate").iter().map(|r| int(&r["loot_id"])).filter(|id| !used_slots.contains(id)).collect();
    unused.dedup();
    if !unused.is_empty() {
        groups.push(EGroup { loot_ids: unused, limit: 0, maps: vec![0], types: vec![0], srcs: vec![] });
    }

    let mut all_maps: Vec<i64> = groups.iter().flat_map(|g| g.maps.clone()).collect();
    all_maps.sort();
    all_maps.dedup();
    let maps_label = |maps: &[i64]| -> String {
        if maps == [0] {
            String::new()
        } else if maps == all_maps.as_slice() {
            "все карты: ".into()
        } else {
            format!("{}: ", maps.iter().map(|m| map_label(*m)).collect::<Vec<_>>().join(", "))
        }
    };

    let mut t = String::from(DOC);
    let mut missing_slots = 0;
    let width = if groups.len() >= 100 { 3 } else { 2 };
    for (gi, g) in groups.iter().enumerate() {
        let gname = match g.srcs.first() {
            None => "слоты без источника (могут вызываться по id напрямую) — не удалять".to_string(),
            Some(s0) => {
                let first = src_name.get(s0).cloned().unwrap_or_else(|| s0.to_string());
                let who = if g.srcs.len() > 1 { format!("{} и ещё {}", first, g.srcs.len() - 1) } else { first };
                let mut prefix = maps_label(&g.maps);
                if g.types != [0] {
                    prefix = format!("{}тип {} — ", prefix, g.types.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(","));
                }
                format!("{}{}", prefix, who)
            }
        };
        let gid = if g.srcs.is_empty() { "no_source".to_string() } else { format!("g{:0w$}", gi + 1, w = width) };
        let _ = writeln!(t, "\n[groups.{}]\nname = {}", gid, tq(&gname));
        let list = |v: &[i64]| v.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(", ");
        if g.maps != [0] {
            let _ = writeln!(t, "maps = [{}]", list(&g.maps));
        }
        if g.types != [0] {
            let _ = writeln!(t, "loot_types = [{}]", list(&g.types));
        }
        if g.limit != 0 {
            let _ = writeln!(t, "limit = {}", g.limit);
        }
        t.push_str("sources = [\n");
        for s in &g.srcs {
            match src_name.get(s) {
                Some(n) if our_src.contains(n) => {
                    let _ = writeln!(t, "  {},  # {}", tq(n), s);
                }
                Some(n) => {
                    let _ = writeln!(t, "  {},  # {} — not in our loot_source_map", s, n);
                }
                None => {
                    let _ = writeln!(t, "  {},  # not in loot_source_map", s);
                }
            }
        }
        t.push_str("]\nslots = [\n");
        for &lid in &g.loot_ids {
            let Some(sl) = slots.get(&lid) else {
                missing_slots += 1;
                let _ = writeln!(t, "  # slot {} not found in loot_choose_group_rate — skipped", lid);
                continue;
            };
            let rids: Vec<i64> = sl["random_ids"].as_array().into_iter().flatten().map(int).collect();
            let pr: Vec<i64> = sl["pr"].as_array().into_iter().flatten().map(int).collect();
            let (rate, max) = (int(&sl["default_rate"]), int(&sl["max_rate"]));
            let mut parts = vec![format!("id = {}", lid)];
            if rids.len() == 1 {
                parts.push(format!("pool = {}", rids[0]));
            } else {
                parts.push(format!("pools = [{}]", rids.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(", ")));
            }
            if !(rids.len() == 1 && pr == [100]) && !pr.is_empty() {
                parts.push(format!("pr = [{}]", pr.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(", ")));
            }
            parts.push(format!("chance = {}", pct(rate)));
            if max != rate {
                parts.push(format!("max = {}", pct(max)));
            }
            for f in ["condition", "rare_pool"] {
                if sl[f].as_array().map(|a| !a.is_empty()).unwrap_or(false) {
                    parts.push(format!("{} = {}", f, inline(&sl[f])));
                }
            }
            let label = rids.iter().map(|r| pool_names.get(r).cloned().unwrap_or_else(|| "no pool".into())).collect::<Vec<_>>().join(" | ");
            let _ = writeln!(t, "  {{ {} }},  # {}", parts.join(", "), label);
        }
        t.push_str("]\n");
    }

    for (rid, entries) in &pools {
        let _ = writeln!(t, "\n[pools.{}]\nname = {}", rid, tq(&pool_names[rid]));
        for (k, v) in pool_extra.get(rid).into_iter().flatten() {
            let _ = writeln!(t, "{} = {}", tkey(k), inline(v));
        }
        t.push_str("items = [\n");
        for e in entries {
            let mut parts = vec![format!("id = {}", e.item)];
            if e.cnts != [1] {
                if e.cnts.len() == 1 {
                    parts.push(format!("cnt = {}", e.cnts[0]));
                } else {
                    parts.push(format!("cnt = [{}]", e.cnts.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(", ")));
                }
            }
            parts.push(format!("w = {}", e.rate * e.cnts.len() as i64));
            if e.level != 1 {
                parts.push(format!("level = {}", e.level));
            }
            let _ = writeln!(t, "  {{ {} }},  # {}", parts.join(", "), item_label(e.item));
        }
        t.push_str("]\n");
    }

    std::fs::create_dir_all(out.parent().unwrap()).unwrap();
    std::fs::write(out, &t).unwrap();
    println!("{} groups, {} pools -> {}", groups.len(), pools.len(), TEMPLATE);
    if !skipped_maps.is_empty() {
        skipped_maps.sort();
        println!(
            "  skipped maps that are not in our map_detail ({}): {} — all maps: --maps=all",
            skipped_maps.len(),
            skipped_maps.iter().take(12).map(|m| m.to_string()).collect::<Vec<_>>().join(", ")
        );
    }
    if missing_slots > 0 {
        println!("  {} references to missing slots skipped", missing_slots);
    }
    true
}

