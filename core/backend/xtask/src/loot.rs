/// Loot source type by blueprint name
fn source_kind(name: &str) -> &'static str {
    let n = name.to_lowercase();
    if n.bytes().all(|c| c.is_ascii_digit()) {
        "other"
    } else if n.contains("monster") || n.starts_with("bp_tgf_m_") {
        "monster"
    } else if n.contains("chest") {
        "chest"
    } else if n.contains("altar") {
        "altar"
    } else if n.contains("collectable") || n.contains("loot_gold") {
        "pickup"
    } else {
        "container"
    }
}

const SOURCE_KINDS: [(&str, &str, &str); 6] = [
    ("monster", "Монстры", "Monsters"),
    ("chest", "Сундуки", "Chests"),
    ("container", "Ящики, бочки, вазы", "Crates, barrels, vases"),
    ("altar", "Алтари", "Altars"),
    ("pickup", "Предметы на земле", "Pickups"),
    ("other", "Прочие источники", "Other sources"),
];

/// BP_TGF_H_Monster_Goblin_Axe_C -> Goblin Axe (H): without the service parts of the name
fn source_label(name: &str) -> String {
    let mut n = name.strip_suffix("_C").unwrap_or(name).strip_prefix("BP_").unwrap_or(name);
    let mut hard = false;
    for prefix in ["TGF_", "Tgf_", "H_", "M_", "Monster_", "TreasureChest_", "CollectableBase_"] {
        if let Some(rest) = n.strip_prefix(prefix) {
            hard |= prefix == "H_";
            n = rest;
        }
    }
    let label = n.replace('_', " ");
    if hard {
        format!("{} (H)", label)
    } else {
        label
    }
}

fn source_text(v: &Json) -> String {
    match v {
        Json::String(s) => s.clone(),
        other => other.to_string(),
    }
}

/// Group label: source type and the first sources. Sources have no names from the game, so these are blueprint names.
fn group_labels(g: &Json) -> (String, String, &'static str, Vec<String>) {
    let sources: Vec<String> = g["sources"].as_array().into_iter().flatten().map(source_text).collect();
    if sources.is_empty() {
        return ("Без источника".into(), "No source".into(), "other", sources);
    }
    let mut counts: Vec<(&'static str, usize)> = Vec::new();
    for s in &sources {
        let k = source_kind(s);
        match counts.iter_mut().find(|c| c.0 == k) {
            Some(c) => c.1 += 1,
            None => counts.push((k, 1)),
        }
    }
    let kind = counts.iter().max_by_key(|c| c.1).map_or("other", |c| c.0);
    let (_, ru, en) = SOURCE_KINDS.iter().find(|k| k.0 == kind).copied().unwrap();
    let pretty: Vec<String> = sources.iter().map(|s| source_label(s)).collect();
    let shown = pretty.iter().take(2).cloned().collect::<Vec<_>>().join(", ");
    let rest = pretty.len().saturating_sub(2);
    let (ru, en) = if rest == 0 { (format!("{}: {}", ru, shown), format!("{}: {}", en, shown)) } else { (format!("{}: {} и ещё {}", ru, shown, rest), format!("{}: {} and {} more", en, shown, rest)) };
    (ru, en, kind, pretty)
}

/// Template table values in one language
pub fn template_values(doc: &Json, cats: &HashMap<i64, Cat>, names: Option<&Names>, en: bool) -> Vec<(&'static str, Vec<balance_kit::Value>)> {
    let item = |id: i64| names.and_then(|n| n.item_localized(id)).map_or_else(|| id.to_string(), str::to_string);
    let group = |_: &str, g: &Json| {
        let (ru, english, ..) = group_labels(g);
        if en { english } else { ru }
    };
    let pool = |k: &str, p: &Json| {
        if en {
            balance_kit::loot::pool_label_en(k, p, cats)
        } else {
            p["name"].as_str().unwrap_or(k).to_string()
        }
    };
    balance_kit::loot::template_tables(doc, &balance_kit::loot::Labels { item: &item, group: &group, pool: &pool })
}

/// raw/loot_template.json: the template and what the app needs to compute the drop
pub fn template_json(doc: &Json) -> Json {
    let cats = item_cats();
    let prices = item_prices();
    let mut used: HashSet<i64> = doc["pools"].as_object().into_iter().flatten().flat_map(|(_, p)| p["items"].as_array().into_iter().flatten().map(|i| int(&i["id"]))).collect();
    // Rules may remove an item by id
    used.extend(doc["rules"]["remove"].as_array().into_iter().flatten().filter(|x| x.is_number()).map(int));
    let mut groups = Map::new();
    for (k, g) in doc["groups"].as_object().into_iter().flatten() {
        let (ru, en, kind, sources) = group_labels(g);
        groups.insert(k.clone(), json!({ "ru": ru, "en": en, "kind": kind, "sources": sources }));
    }
    let mut ids: Vec<i64> = used.into_iter().collect();
    ids.sort();
    json!({
        "format": balance_kit::loot::TEMPLATE_FORMAT,
        "template": doc,
        "cats": ids.iter().filter_map(|id| cats.get(id).map(|c| (id.to_string(), json!(cat_code(*c))))).collect::<Map<_, _>>(),
        "prices": ids.iter().filter_map(|id| prices.get(id).map(|p| (id.to_string(), json!(p)))).collect::<Map<_, _>>(),
        "kinds": SOURCE_KINDS.iter().map(|k| json!({ "id": k.0, "ru": k.1, "en": k.2 })).collect::<Vec<_>>(),
        "groups": groups
    })
}

/// The new template text is checked by a build: the same as `loot build` does, but without writing the tables
pub fn validate_template(season: Option<&str>, text: &str) -> Result<Vec<String>, Vec<String>> {
    let s = Schema::load();
    compile_text(&s, &target(season), text).map(|c| c.notes)
}

/// Table template values as check data: values only
fn template_data(doc: &Json) -> std::collections::BTreeMap<String, balance_kit::TableData> {
    template_values(doc, &item_cats(), None, false).into_iter().map(|(name, values)| (name.to_string(), balance_kit::TableData { values, ..Default::default() })).collect()
}
