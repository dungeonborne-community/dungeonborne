// Loot from the template loot\loot.toml (details — BALANCE.md, "Loot").
//
// How loot works in the game tables:
//   source (chest/monster, id from loot_source_map) --loot_ue_source_choose_group--> slots (loot_id)
//   slot --loot_choose_group_rate--> a roll with chance default_rate/10000, then a pool (random_ids by weights pr)
//   pool --loot--> ONE item by weights rate (sum of the pool weights = 30000), cnt — the count
//   loot_rate — extra pool fields (unlucky/corruption), a row per pool.
// The template describes the same in human terms: source groups with slots and pools with items,
// plus [rules] — edits on top of everything (remove a category, multiply chance/weight/count).
