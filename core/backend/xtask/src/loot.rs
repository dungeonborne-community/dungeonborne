// ---------- item categories (by item_type) ----------

pub fn item_cats() -> HashMap<i64, Cat> {
    let mut out = HashMap::new();
    for r in rows_in(BALANCE, "item_type") {
        let Some(id) = r["type_id"].as_i64() else { continue };
        let major = r["item_major_type"].as_str().unwrap_or("");
        let minor = r["item_minor_type"].as_str().unwrap_or("");
        let c = if id == 100069 {
            Cat::Gold
        } else if minor == "EN_ITEM_MINOR_TYPE_EQUIPMENT_WEAPON" {
            Cat::Weapon
        } else if minor == "EN_ITEM_MINOR_TYPE_EQUIPMENT_ARMOR" {
            Cat::Armor
        } else if minor == "EN_ITEM_MINOR_TYPE_EQUIPMENT_ACCESSORIES" {
            Cat::Jewelry
        } else if major == "EN_ITEM_MAJOR_TYPE_GEM" {
            Cat::Gem
        } else if major == "EN_ITEM_MAJOR_TYPE_CRAFTS" {
            Cat::Treasure
        } else if minor == "EN_ITEM_MINOR_TYPE_CONSUMABLES_POTION" {
            Cat::Potion
        } else if minor == "EN_ITEM_MINOR_TYPE_CONSUMABLES_THROWABLE" {
            Cat::Throwable
        } else if major == "EN_ITEM_MAJOR_TYPE_CONSUMABLES" {
            Cat::Supply
        } else if major == "EN_ITEM_MAJOR_TYPE_CURRENCY" {
            Cat::Currency
        } else {
            Cat::Other
        };
        out.insert(id, c);
    }
    out
}

// ---------- common ----------

fn rows_in(dir: &str, table: &str) -> Vec<Json> {
    tables::read_json(&Path::new(dir).join(format!("{}.json", table)))
        .ok()
        .and_then(|v| v["rows"].as_array().cloned())
        .unwrap_or_default()
}

fn int(v: &Json) -> i64 {
    v.as_i64().unwrap_or(0)
}

fn tq(s: &str) -> String {
    serde_json::to_string(s).unwrap() // a JSON string is a valid TOML basic string
}

fn tkey(k: &str) -> String {
    if !k.is_empty() && k.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-') {
        k.to_string()
    } else {
        tq(k)
    }
}

/// JSON -> an inline TOML value (for fields the template carries as is: condition, rare_pool…)
fn inline(v: &Json) -> String {
    match v {
        Json::Null => "{}".into(),
        Json::Bool(b) => b.to_string(),
        Json::Number(n) => n.to_string(),
        Json::String(s) => tq(s),
        Json::Array(a) => format!("[{}]", a.iter().map(inline).collect::<Vec<_>>().join(", ")),
        Json::Object(o) => {
            if o.is_empty() {
                "{}".into()
            } else {
                format!("{{ {} }}", o.iter().map(|(k, v)| format!("{} = {}", tkey(k), inline(v))).collect::<Vec<_>>().join(", "))
            }
        }
    }
}

/// chance in percent: 3500 -> "35", 50 -> "0.5"
fn pct(rate: i64) -> String {
    if rate % 100 == 0 {
        (rate / 100).to_string()
    } else {
        format!("{}", rate as f64 / 100.0)
    }
}

fn cnt_range(cnts: &[i64]) -> String {
    let (lo, hi) = (cnts.iter().min().copied().unwrap_or(1), cnts.iter().max().copied().unwrap_or(1));
    if lo == hi {
        if lo == 1 { String::new() } else { format!(" ×{}", lo) }
    } else {
        format!(" ×{}–{}", lo, hi)
    }
}

