-- Mods/ClientProbe/Scripts/main.lua
-- A log of what the client does with server responses (the pair to the server-side RPC_DUMP=1):
--   EVT  — client events (descendants of UTGFEventArgs) with fields: ErrorCode, TGFRsp (the server response as a UObject), etc.
--   WIN  — opened windows (UTGFWindowArgs: texts of alerts and toasts)
--   CALL — calls of service functions (UTGFService) and helper classes with arguments — what the UI requests
--   ERR  — display of protocol errors (PromptProtocolError/GetProtocolErrorText), toasts, alerts
--   SNAP — F10: a snapshot of the fields of all services (what the client kept from our responses); MARK — F11: a user marker
-- Line format (shared with the Lua probe from the pak): <epoch_ms>\t<seq>\tue4ss\t<type>\t<text>.
-- File: <log_dir>/<client>_<date-time>_ue4ss.log — each client has its own (two installs write in parallel).
-- Client: config name=…, otherwise by local_save.txt in Win64 ("alt" — the second client C:\Games\Dungeonborne, otherwise "steam").
-- Targets (classes) — targets.lua, generated by tools/gen_probe_targets.py from CXXHeaderDump.
-- Settings — Mods/ClientProbe/config.txt (read at game start).

