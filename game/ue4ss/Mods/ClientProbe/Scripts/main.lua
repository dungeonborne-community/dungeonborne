local MESH_CLASSES = { SkeletalMeshComponent = true, StaticMeshComponent = true, PoseableMeshComponent = true }
local function IsMesh(c)
    MeshCls = (Ok(MeshCls) and MeshCls) or StaticFindObject("/Script/Engine.MeshComponent")
    local isa = Ok(MeshCls) and Get(function() return c:IsA(MeshCls) end)
    if isa ~= nil then return isa end
    local cls = Get(function() return c:GetClass():GetFName():ToString() end) or ""
    return MESH_CLASSES[cls] == true
end

-- hero meshes: ACharacter.Mesh and everything attached to it (AttachChildren), at most 40 components
local function EachMesh(pawn, fn)
    local root = Get(function() return pawn.Mesh end)
    if not Ok(root) then return end
    local q, seen, n = { root }, {}, 0
    while #q > 0 and n < 40 do
        local c = table.remove(q, 1)
        n = n + 1
        local a = Addr(c)
        if Ok(c) and not seen[a] then
            seen[a] = true
            if IsMesh(c) then fn(c) end
            pcall(function()
                c.AttachChildren:ForEach(function(_, e)
                    local k = e:get()
                    if Ok(k) then q[#q + 1] = k end
                end)
            end)
        end
    end
end

local function MatStr(mc, tag, m)
    if not Ok(m) then return nil end
    local cls = Get(function() return m:GetClass():GetFName():ToString() end) or "?"
    if cls == "MaterialInstanceDynamic" then
        return string.format("%s[%s]=%s<%s>", tag, ObjName(mc), MidParams(m), ObjName(Get(function() return m.Parent end)))
    end
    return string.format("%s[%s]=%s:%s", tag, ObjName(mc), cls, ObjName(m))
end
local StlWas = {} -- state address → was active at the previous check

local function StealthTick()
    local states = Get(function() return FindAllOf("BP_MaterialState_Stealth_C") end) or {}
    -- the own player via LyraTeamSubsystem (as in the BP) and for comparison — the first local controller
    if not Ok(TeamSub) then
        TeamSub = nil
        for _, s in ipairs(Get(function() return FindAllOf("LyraTeamSubsystem") end) or {}) do
            if Ok(s) and not ObjName(s):find("Default__", 1, true) then TeamSub = s; break end
        end
    end
    local Own = TeamSub and Get(function() return TeamSub:GetOwnPlayer() end) or nil
    local OwnLocal = Ok(Own) and Get(function() return Own:IsLocalPlayerController() end)
    local OwnPawn = Ok(Own) and Get(function() return Own.Pawn end) or nil
    local OwnPS = Ok(Own) and Get(function() return Own.PlayerState end) or nil
    local ox, oy, oz = nil, nil, nil
    if Ok(OwnPawn) then ox, oy, oz = Loc(OwnPawn) end
    local Seen = {}
    local RampNew = {}
    RampOwn = OwnPawn
    for _, st in ipairs(states) do
        if Ok(st) and not ObjName(st):find("Default__", 1, true) then
            local a = Addr(st)
            local mgr = Get(function() return st.Owner:Get() end)
            if not Ok(mgr) then mgr = Get(function() return st.Owner end) end -- a weak reference may come as an object
            local cur = Ok(mgr) and Get(function() return mgr.CurrentMaterialState end) or nil
            local active = Ok(cur) and Addr(cur) == a
            local tick = Get(function() return st.bTickEnabled end)
            if active or StlWas[a] then
                Seen[a] = active or nil
                local pawn = Ok(mgr) and Get(function() return mgr:GetOwner() end) or nil
                local ps = Ok(pawn) and Get(function() return pawn.PlayerState end) or nil
                local dist = "-"
                if ox and Ok(pawn) then
                    local x, y, z = Loc(pawn)
                    if x then dist = string.format("%.0f", math.sqrt((x - ox) ^ 2 + (y - oy) ^ 2 + (z - oz) ^ 2)) end
                end
                local mids = {}
                local cloakv = Ok(mgr) and Get(function() return mgr.CloakType end) or nil
                local cloak = Ok(mgr) and Get(function() return mgr.CharacterEnemyCloakingMatDynamic end) or nil
                if Ok(cloak) then mids[#mids + 1] = "cloak=" .. MidParams(cloak) end
                -- 12.11 (LOCAL analysis): in UE4SS 3.0.1 a function's array result and TMap do not work from Lua — meshes by walking
                -- properties (ACharacter.Mesh → AttachChildren), the ASC via AbilitySystemBlueprintLibrary (like Hall.HasNoDamage)
                if Ok(pawn) then
                    local seenM, detail, parts = {}, 0, {}
                    RampMids = {}
                    -- 12.11: the threshold is set on ALL stealth MIDs of the hero (before it hit the line limit — the body did not get it),
                    -- the log gets a summary per mesh: name, visible or not, materials, stealth MIDs among them, how many were set
                    EachMesh(pawn, function(mc)
                        local n = Get(function() return mc:GetNumMaterials() end) or 0
                        local inv, set, other, fars = 0, 0, nil, {}
                        RampMids = RampMids or {}
                        local list = {}
                        for i = 0, math.min(n, 16) - 1 do list[#list + 1] = { "#" .. i, Get(function() return mc:GetMaterial(i) end) } end
                        list[#list + 1] = { "ov", Get(function() return mc.OverlayMaterial end) }
                        for _, e in ipairs(list) do
                            local m = e[2]
                            if Ok(m) then
                                local isInv = ObjName(Get(function() return m.Parent end)) == "MI_Character_CharacterInvisibility_Albedo_Distance"
                                if isInv then
                                    local fv = Get(function() return m:K2_GetScalarParameterValue(FName("FarDistanceVisibility")) end)
                                    local tv = Get(function() return m:K2_GetScalarParameterValue(FName("StealthVisibleDistance")) end)
                                    fars[#fars + 1] = string.format("%s/%s", Num(tv), Num(fv))
                                    if StlRamp > 0 and (cloakv == 2 or cloakv == 3) then RampMids[#RampMids + 1] = m end
                                    inv = inv + 1
                                    if StlVis > 0 and (cloakv == 2 or cloakv == 3) then
                                        if StlFar then pcall(function() m:SetScalarParameterValue(FName("FarDistanceVisibility"), StlFar) end) end
                                        for _, pv in ipairs(StlSet) do
                                            pcall(function() m:SetScalarParameterValue(FName(pv[1]), pv[2]) end)
                                        end
                                        local okv = pcall(function() m:SetScalarParameterValue(FName("StealthVisibleDistance"), StlVis) end)
                                        if okv then set = set + 1 elseif Allowed("stl_vis_err", 5) then W("WARN", "stealth: SetScalarParameterValue failed") end
                                    end
                                    if detail < 2 and not seenM[Addr(m)] then
                                        detail = detail + 1
                                        mids[#mids + 1] = MatStr(mc, "inv" .. e[1], m)
                                    end
                                elseif not other then
                                    other = ObjName(m)
                                end
                                seenM[Addr(m)] = true
                            end
                        end
                        local vis = Get(function() return mc:IsVisible() end)
                        local hid = Get(function() return mc.bHiddenInGame end)
                        parts[#parts + 1] = string.format("%s(vis=%s hid=%s mat=%d inv=%d set=%d%s%s)", ObjName(mc), tostring(vis),
                            tostring(hid), n, inv, set, other and (" first=" .. other) or "",
                            #fars > 0 and (" thr/far=" .. table.concat(fars, ",")) or "")
                    end)
                    mids[#mids + 1] = "parts[" .. table.concat(parts, " ") .. "]"
                    if #RampMids > 0 then RampNew[#RampNew + 1] = { pawn = pawn, mids = RampMids } end
                end
                local asc = AscOf(pawn, ps)
                local tags = {}
                for _, t in ipairs(STL_TAGS) do
                    local has = asc and Get(function() return asc:HasMatchingGameplayTag({ TagName = FName(t[2]) }) end)
                    tags[#tags + 1] = t[1] .. "=" .. (asc and tostring(has) or "noasc")
                end
                mids[#mids + 1] = "tags[" .. table.concat(tags, " ") .. "]"
                -- the MID of the state itself: GetMID(FString) — a string parameter, off by default (stealth_getmid = 1)
                if Cfg.stealth_getmid == "1" then
                    for _, key in ipairs({ "Main", "Overlay" }) do
                        local m = Get(function() return st:GetMID(key) end)
                        mids[#mids + 1] = "state." .. key .. "=" .. (Ok(m) and MidParams(m) or "null")
                    end
                end
                local fade = Ok(mgr) and Get(function() return mgr.CharacterFadeOutMatDynamic end) or nil
                mids[#mids + 1] = "fadeMID=" .. (Ok(fade) and ObjName(fade) or "null")
                W("STL", string.format(
                    "%s pawn=%s team=%s active=%s tick=%s cloak=%s mat=%s | own=%s local=%s own_pawn=%s own_team=%s | dist=%s | %s",
                    a == 0 and "?" or string.format("%x", a), ObjName(pawn), TeamOf(ps), tostring(active), tostring(tick),
                    Num(Ok(mgr) and Get(function() return mgr.CloakType end)), Num(Ok(mgr) and Get(function() return mgr.MaterialType end)),
                    ObjName(Own), tostring(OwnLocal), ObjName(OwnPawn), TeamOf(OwnPS), dist,
                    #mids > 0 and table.concat(mids, " ") or "mid=none"), 16000)
            end
        end
    end
    StlWas = Seen
    Ramp = RampNew
end

-- smooth visibility (stl_ramp): more often than the once-a-second check, only writing one parameter into already found MIDs
local RampLog = 0
local function RampTick()
    if StlRamp <= 0 or #Ramp == 0 or not Ok(RampOwn) then return end
    local ox, oy, oz = Loc(RampOwn)
    if not ox then return end
    for _, r in ipairs(Ramp) do
        if Ok(r.pawn) then
            local x, y, z = Loc(r.pawn)
            if x then
                local d = math.sqrt((x - ox) ^ 2 + (y - oy) ^ 2 + (z - oz) ^ 2)
                local v = math.max(0, math.min(1, 1 - d / StlRamp))
                for _, m in ipairs(r.mids) do
                    if Ok(m) then pcall(function() m:SetScalarParameterValue(FName("FarDistanceVisibility"), v) end) end
                end
                if os.time() ~= RampLog then
                    RampLog = os.time()
                    W("STLR", string.format("pawn=%s dist=%.0f far=%.3f mids=%d", ObjName(r.pawn), d, v, #r.mids))
                end
            end
        end
    end
end

local StealthLoop, RampLoop
if StealthOn and StlRamp > 0 then
    ExecuteInGameThread(function() RampLoop = LoopInGameThreadWithDelay(100, function()
        if Phase == "off" then CancelDelayedAction(RampLoop); return end
        if Phase ~= "on" then return end
        local ok, err = pcall(RampTick)
        if not ok and Allowed("stl_ramp_err", 20) then W("WARN", "stealth ramp: " .. tostring(err)) end
    end) end)
end
if StealthOn then
    ExecuteInGameThread(function() StealthLoop = LoopInGameThreadWithDelay(1000, function()
        if Phase == "off" then CancelDelayedAction(StealthLoop); return end
        if Phase ~= "on" then return end
        local ok, err = pcall(StealthTick)
        if not ok and Allowed("stl_err", 20) then W("WARN", "stealth: " .. tostring(err)) end
    end) end)
end
