local LogPath, Out = nil, nil
local function OpenLog()
    LogPath = string.format("%s/%s_%s_ue4ss.log", Cfg.log_dir, ClientName, os.date("%Y%m%d-%H%M%S"))
    Out = io.open(LogPath, "w")
    if not Out then
