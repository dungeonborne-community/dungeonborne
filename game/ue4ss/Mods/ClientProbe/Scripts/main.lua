            ClientName, os.date("%Y%m%d-%H%M%S"))
        Out = io.open(LogPath, "w")
    end
end
local Seq, Lines = 0, 0

local function W(kind, text, maxlen)
    if not Out or Lines >= MaxLines then return end
    Seq = Seq + 1
    Lines = Lines + 1
    local s = tostring(text):gsub("[\r\n\t]", " ")
    maxlen = maxlen or 8000
    if #s > maxlen then s = s:sub(1, maxlen) .. "..." end
    Out:write(NowMs(), "\t", Seq, "\tue4ss\t", kind, "\t", s, "\n")
    Out:flush()
end


-- ---------------------------------------------------------------- value dump

local function PropName(p)
    local ok, n = pcall(function() return p:GetFName():ToString() end)
    return ok and n or "?"
end

local function PropKind(p)
    local ok, n = pcall(function() return p:GetClass():GetFName():ToString() end)
    return ok and n or "?"
end

-- 31.10: strings (FString/FText) of live objects and parameters are NOT read — reading via UE4SS corrupted the game heap
-- (crash "FMallocBinned2 Attempt to realloc an unrecognized block" after dumping UserNickName on login).
-- Safe: numbers, bool, FName (index in the name table), class names. Window/toast texts are logged by the Lua probe.
local UNSAFE_KINDS = { StrProperty = "<str>", TextProperty = "<text>" }

local function Scalar(v)
    local t = type(v)
    if t == "number" then
        if v == math.floor(v) and math.abs(v) < 2 ^ 53 then return string.format("%d", v) end
        return string.format("%.4g", v)
    end
    if t ~= "userdata" then return tostring(v) end
    local okt, ut = pcall(function() return v:type() end)
    if not okt then return "<?>" end
    if ut == "FName" then
        local ok, s = pcall(function() return v:ToString() end)
        return ok and ('"' .. s .. '"') or "<FName>"
    end
    return "<" .. tostring(ut) .. ">"
end

-- All properties of a struct/class together with parents (up to UObject)
local function ForEachProp(struct, fn)
    local cur, guard = struct, 0
    while cur and guard < 16 do
        guard = guard + 1
        local ok, valid = pcall(function() return cur:IsValid() end)
        if not ok or not valid then break end
        local name = cur:GetFName():ToString()
        if name == "Object" then break end
        pcall(function() cur:ForEachProperty(fn) end)
        local okn, nxt = pcall(function() return cur:GetSuperStruct() end)
        cur = okn and nxt or nil
    end
end

local DumpProp

-- We go deep only into the root object (an event, window arguments, a service in a snapshot) and into protocol data
-- (TGFProto*): for other objects (widgets, animations…) only the class is logged.
local function DumpObject(obj, depth, root)
    if obj == nil then return "nil" end
    local ok, valid = pcall(function() return obj:IsValid() end)
    if not ok or not valid then return "null" end
    local cls = obj:GetClass()
    local cname = cls:GetFName():ToString()
    if depth <= 0 or not (root or cname:sub(1, 8) == "TGFProto") then return cname end
    local parts = {}
    ForEachProp(cls, function(p)
        if #parts >= 80 then return end
        local n = PropName(p)
        local okv, v = pcall(function() return obj[n] end)
        parts[#parts + 1] = n .. "=" .. (okv and DumpProp(p, v, depth - 1) or "?")
    end)
    return cname .. "{" .. table.concat(parts, ", ") .. "}"
end

DumpProp = function(p, v, depth)
    local k = PropKind(p)
    if UNSAFE_KINDS[k] then return UNSAFE_KINDS[k] end
    local ok, s = pcall(function()
        if k == "ObjectProperty" then
            return DumpObject(v, depth)
        elseif k == "StructProperty" then
            local st = p:GetStruct()
            if depth < 0 then return st:GetFName():ToString() end
            local parts = {}
            ForEachProp(st, function(fp)
                if #parts >= 80 then return end
                local fname = PropName(fp)
                local okf, fv = pcall(function() return v[fname] end)
                parts[#parts + 1] = fname .. "=" .. (okf and DumpProp(fp, fv, depth - 1) or "?")
            end)
            return "{" .. table.concat(parts, ", ") .. "}"
        elseif k == "ArrayProperty" then
            local n = v:GetArrayNum()
            local parts = {}
            local inner = p:GetInner()
            if depth >= 0 and n > 0 and not UNSAFE_KINDS[PropKind(inner)] then
                v:ForEach(function(i, e)
                    if i <= 8 then parts[#parts + 1] = DumpProp(inner, e:get(), depth - 1) end
                end)
            end
            return "[" .. n .. "]" .. (#parts > 0 and ("{" .. table.concat(parts, "; ") .. "}") or "")
        elseif k == "MapProperty" or k == "SetProperty" or k == "DelegateProperty" or k == "MulticastInlineDelegateProperty"
            or k == "MulticastSparseDelegateProperty" then
            return "<" .. k .. ">"
        else
            return Scalar(v) or ("<" .. k .. ">")
        end
    end)
    return ok and s or ("<" .. k .. "!>")
end

-- ---------------------------------------------------------------- rate limit

local Counts = {}
local function Allowed(key, limit)
    local c = (Counts[key] or 0) + 1
    Counts[key] = c
    if c <= limit or c % 500 == 0 then return true, c end
    return false, c
end

local function Short(path)
    return path:match("%.([%w_]+)$") or path
end

-- ---------------------------------------------------------------- events and windows

local function WatchObjects(list, kind)
    local n = 0
    for _, path in ipairs(list or {}) do
        local short = Short(path)
        local ok = pcall(function()
            NotifyOnNewObject(path, function(obj)
                local allowed, c = Allowed(kind .. short, EventLimit)
                if not allowed then return end
                -- the fields are filled right after NewObject — read them on the nearest game-thread step
                ExecuteInGameThread(function()
                    local okd, s = pcall(DumpObject, obj, EventDepth, true)
                    W(kind, short .. " " .. (okd and s or "?") .. (c > EventLimit and (" #" .. c) or ""))
                end)
            end)
        end)
        if ok then n = n + 1 else W("WARN", "NotifyOnNewObject did not attach: " .. path) end
    end
    return n
end

-- ---------------------------------------------------------------- service functions

local Hooked = {}
local function Skip(name)
    for _, s in ipairs(SkipList) do
        if name:find(s, 1, true) then return true end
    end
    return false
end

local function KindOf(short)
    if short:find("ProtocolError") or short:find("ShowToast") or short:find("ShowAlert") or short:find("ShowConfirm") then
        return "ERR"
    end
    return "CALL"
end

-- Parameters that UE4SS passes to the hook without copying containers
local SIMPLE_KINDS = {
    BoolProperty = true, ByteProperty = true, EnumProperty = true, NameProperty = true,
    IntProperty = true, Int8Property = true, Int16Property = true, Int64Property = true,
    UInt16Property = true, UInt32Property = true, UInt64Property = true, FloatProperty = true, DoubleProperty = true,
    ObjectProperty = true, ClassProperty = true,
}
local SkippedComplex = 0

local function HookClass(path)
    local cls = StaticFindObject(path)
    if not (cls and cls:IsValid()) then return nil end
    local n = 0
    cls:ForEachFunction(function(fn)
        local full = fn:GetFullName():match("^Function%s+(.+)$")
        if not full or Hooked[full] then return end
        local short = full:match("%.([%w_]+:[%w_]+)$") or full
        if Skip(short) then return end
        local props, simple = {}, true
        pcall(function()
            fn:ForEachProperty(function(p)
                if not SIMPLE_KINDS[PropKind(p)] then simple = false end
                if PropName(p) ~= "ReturnValue" then props[#props + 1] = p end
            end)
        end)
        -- 31.10: with hooks on functions with containers (TArray/FString/structs, including out parameters and the result)
        -- UE4SS corrupted the game heap on the call (crash on login). By default only simple signatures are hooked.
        if not simple and Cfg.hook_params ~= "all" then
            SkippedComplex = SkippedComplex + 1
            return
        end
        local kind = KindOf(short)
        local ok = pcall(function()
            RegisterHook(full, function(self, ...)
                local allowed, c = Allowed(short, kind == "ERR" and 100000 or CallLimit)
                if not allowed then return end
                local args = {}
                for i, prm in ipairs({ ... }) do
                    local p = props[i]
                    local unsafe = p and UNSAFE_KINDS[PropKind(p)]
                    local val = unsafe or "?"
                    if not unsafe then -- a string parameter is not even get()-ed
                        local okg, v = pcall(function() return prm:get() end)
                        if okg then val = (p and DumpProp(p, v, ArgDepth)) or Scalar(v) or "?" end
                    end
                    args[#args + 1] = (p and PropName(p) or ("a" .. i)) .. "=" .. val
                end
                W(kind, short .. "(" .. table.concat(args, ", ") .. ")" .. (c > CallLimit and (" #" .. c) or ""))
            end)
        end)
        if ok then
            Hooked[full] = true
            n = n + 1
        end
    end)
    return n
end

local Pending = {}
local function HookServices()
    local total, missing = 0, {}
    for _, path in ipairs(Pending) do
        local ok, n = pcall(HookClass, path)
        if ok and n then total = total + n else missing[#missing + 1] = path end
    end
    Pending = missing
    return total
end

