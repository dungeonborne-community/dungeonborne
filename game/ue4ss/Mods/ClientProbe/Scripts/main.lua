-- os.clock in MSVC is wall time since process start; we bind it to os.time at a second change (LoopAsync below)
local T0, C0 = os.time(), os.clock()
local function NowMs()
    return math.floor(T0 * 1000 + (os.clock() - C0) * 1000)
end

