-- Start — in the game thread, when the KismetSystemLibrary CDO is available: the command line first. Auto instances
-- (-dbserver / -dbclient, see DungeonborneRuServer) are left alone by the probe: no log, no subscriptions, no hooks.
local SkipCmd = {}
for x in (Cfg.skip_cmdline or ""):gmatch("[^;%s]+") do SkipCmd[#SkipCmd + 1] = x:lower() end
local Phase, Queued = "wait", false

local function Start()
    Queued = false
    if Phase ~= "wait" then return end
    local lib = StaticFindObject("/Script/Engine.Default__KismetSystemLibrary")
    if not (lib and lib:IsValid()) then return end
    local okc, cmd = pcall(function() return lib:GetCommandLine():ToString() end)
    local padded = " " .. (okc and tostring(cmd):lower() or "") .. " "
    local forced = padded:find(" -dbprobe ", 1, true) ~= nil
    if not forced then
        if not Enabled then
            Phase = "off"
            print("[ClientProbe] disabled (config.txt enabled=0)\n")
            return
        end
        for _, flag in ipairs(SkipCmd) do
            if padded:find(" " .. flag .. " ", 1, true) then
                Phase = "off"
                print("[ClientProbe] " .. flag .. " on the command line — probe disabled\n")
                return
            end
        end
    end
    -- auto instances with -dbprobe: the role in the file name (server and client from one install write in parallel)
    if padded:find(" -dbserver ", 1, true) then
        ClientName = ClientName .. "-srv"
    elseif padded:find(" -dbclient ", 1, true) then
        ClientName = ClientName .. "-cli"
    end
    Phase = "on"
    OpenLog()
    print("[ClientProbe] log: " .. tostring(LogPath) .. "\n")
    W("HDR", string.format("client=%s steam_id=%s profile=%s script=%s", ClientName, SteamId, Profile or "-", ScriptPath))
    if not Targets then
        W("WARN", "targets.lua not loaded: " .. tostring(loaded))
        return
    end
    if Cfg.events == "1" then W("HDR", "events: " .. WatchObjects(Targets.events, "EVT")) end
    if Cfg.windows == "1" then W("HDR", "windows: " .. WatchObjects(Targets.windows, "WIN")) end
    if Cfg.services == "1" then
        for _, p in ipairs(Targets.services) do Pending[#Pending + 1] = p end
        W("HDR", "hooks: " .. HookServices() .. ", classes not found: " .. #Pending
            .. ", functions with complex parameters skipped: " .. SkippedComplex .. " (hook_params=" .. tostring(Cfg.hook_params) .. ")")
    end
end

-- Waiting for the start, binding time to a second change, retrying hooks for classes that were missing at start
-- 07.11 (docs/CRASH_LONG_PLAY.md): the loop runs in the game thread (was LoopAsync). Stop — CancelDelayedAction:
-- LoopInGameThreadWithDelay does not stop on return true. Calibration by a second change now has frame granularity.
local Calibrated, Retries, NextRetry = false, 0, os.clock() + 10
local StartLoop
-- registration — from the game thread (ExecuteInGameThread): from the mod loading thread it may hang the process
ExecuteInGameThread(function() StartLoop = LoopInGameThreadWithDelay(50, function()
    if Phase == "off" then CancelDelayedAction(StartLoop); return end
    if Phase == "wait" then
        if not Queued then
            Queued = true
            pcall(Start)
        end
        return
    end
    if not Calibrated and os.time() ~= T0 then
        T0, C0 = os.time(), os.clock()
        Calibrated = true
    end
    if Calibrated and (#Pending == 0 or Retries >= 30) then CancelDelayedAction(StartLoop); return end
    if Calibrated and #Pending > 0 and os.clock() >= NextRetry then
        NextRetry = os.clock() + 10
        Retries = Retries + 1
        local ok, n = pcall(HookServices)
        if ok and n > 0 then W("HDR", "hooks (retry): +" .. n .. ", classes left: " .. #Pending) end
    end
end) end)

