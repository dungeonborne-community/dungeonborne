local function ReadConfig()
    local f = io.open(ModDir .. "/config.txt", "r")
    if not f then return end
    for line in f:lines() do
        if not line:match("^%s*[#;]") then
            local k, v = line:match("^%s*([%w_]+)%s*=%s*(.-)%s*$")
            if k then Cfg[k] = v end
        end
    end
    f:close()
end
