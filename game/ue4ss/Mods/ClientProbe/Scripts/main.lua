local function Ok(o)
    if o == nil then return false end
    local ok, v = pcall(function() return o:IsValid() end)
    return ok and v
end

local function Addr(o)
    local ok, a = pcall(function() return o:GetAddress() end)
    return ok and a or 0
end

local function ObjName(o)
    if not Ok(o) then return "null" end
    local ok, n = pcall(function() return o:GetFName():ToString() end)
    return ok and n or "?"
end

local function Get(fn)
    local ok, v = pcall(fn)
    if ok then return v end
    return nil
end

local function Num(v)
    if type(v) ~= "number" then return tostring(v) end
    if v == math.floor(v) then return string.format("%d", v) end
    return string.format("%.3f", v)
end

local function Loc(actor)
    local v = Get(function() return actor:K2_GetActorLocation() end)
    if not v then return nil end
    local x, y, z = Get(function() return v.X end), Get(function() return v.Y end), Get(function() return v.Z end)
    if type(x) ~= "number" then return nil end
    return x, y, z
end

local function TeamOf(ps)
    if not Ok(ps) then return "-" end
    local t = Get(function() return ps.MyTeamID.TeamID end)
    local id = Get(function() return ps.PlayerId end)
    return string.format("%s/pid%s", Num(t), Num(id))
end

local function MidParams(mid)
    if not Ok(mid) then return "null" end
    local parts = {}
    for _, p in ipairs(STL_PARAMS) do
        local v = Get(function() return mid:K2_GetScalarParameterValue(FName(p)) end)
        parts[#parts + 1] = p .. "=" .. Num(v)
    end
    return ObjName(mid) .. "{" .. table.concat(parts, " ") .. "}"
end

