# Install/update of the DbTools task (launching the game and removing mutexes without UAC, tools/stand/README_admin.md).
# Run by a human in PowerShell "Run as administrator". Machine paths are taken from the workspace local.toml:
#   [stand] work -> the task's work folder (request.json, run, logs, runs), [games] steam / client -> installs.
#   powershell -ExecutionPolicy Bypass -File ops\machine\install-dbtools.ps1            # show
#   powershell -ExecutionPolicy Bypass -File ops\machine\install-dbtools.ps1 -Apply     # install (admin)
# Moving the stand into home: in local.toml [stand] work = 'home:runs/stand', then this script with -Apply;
# the contents of the old work folder (logs, runs) can be moved with -MoveFrom <old folder>.
# Several workspaces on one machine (18.11): each run ADDS this workspace to the task (or updates its entry, keyed by
# the work folder); the others stay. -Remove takes this workspace out.
param([switch]$Apply, [string]$MoveFrom = '', [switch]$Remove)
$ErrorActionPreference = 'Stop'
. "$PSScriptRoot\..\..\tools\stand\paths.ps1"     # $Work, Get-Game
$dst = 'C:\ProgramData\DbTools'
$work = $Work -replace '/', '\'
$steam = Get-Game 'steam'
$client = Get-Game 'client'
# the workspaces already in the task (an old config — its one $WorkDir / $Installs)
$cfgPath = Join-Path $dst 'dbtools.config.ps1'
$known = @()
if (Test-Path $cfgPath) {
    $old = & { . $cfgPath; if ($Workspaces) { $Workspaces } elseif ($WorkDir) { @{ WorkDir = $WorkDir; Installs = $Installs } } }
    $known = @($old | Where-Object { $_ -and $_.WorkDir -and ($_.WorkDir -ne $work) })
}
if (-not $Remove) { $known += @{ WorkDir = $work; Installs = @{ steam = $steam; second = $client } } }
$lines = $known | ForEach-Object { "    @{ WorkDir = '$($_.WorkDir)'; Installs = @{ steam = '$($_.Installs.steam)'; second = '$($_.Installs.second)' } }" }
$first = $known | Select-Object -First 1
$cfg = @"
# Generated by ops\machine\install-dbtools.ps1 from the local.toml of each workspace that ran it - do not edit by hand.
`$Workspaces = @(
$($lines -join "`r`n")
)
# the first one also in the old form (a dbtools.ps1 from before 18.11 reads only these)
`$WorkDir = '$($first.WorkDir)'
`$Installs = @{ steam = '$($first.Installs.steam)'; second = '$($first.Installs.second)' }
"@
"DbTools: $dst"
"  this workspace: work folder $work; installs: steam = $steam; second = $client$(if ($Remove) { ' - to be removed' })"
"  workspaces in the task after this: $($known.Count)"
$known | ForEach-Object { "    $($_.WorkDir)" }
if (-not $Apply) { "Nothing changed. To install (admin): -Apply"; return }

$admin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $admin) { throw 'an elevated console ("Run as administrator") is required' }
New-Item -ItemType Directory -Force $dst, $work | Out-Null
if ($MoveFrom -and (Test-Path $MoveFrom)) {
    & robocopy $MoveFrom $work /E /NFL /NDL /NJH /NJS /NP /R:1 /W:1 | Out-Null
    "copied from $MoveFrom (delete the old folder yourself once you have checked)"
}
$stand = Join-Path $WsRoot 'tools\stand'
Copy-Item "$stand\dbtools.ps1", "$stand\killmutex.ps1" $dst -Force
$utf8bom = New-Object System.Text.UTF8Encoding $true
[IO.File]::WriteAllText((Join-Path $dst 'dbtools.config.ps1'), $cfg, $utf8bom)
icacls $dst /inheritance:r /grant:r "*S-1-5-32-544:(OI)(CI)F" "*S-1-5-18:(OI)(CI)F" "*S-1-5-32-545:(OI)(CI)RX" | Out-Null
$a = New-ScheduledTaskAction -Execute powershell.exe -Argument "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File $dst\dbtools.ps1"
$p = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\$env:USERNAME" -RunLevel Highest -LogonType Interactive
$s = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -ExecutionTimeLimit (New-TimeSpan -Minutes 2)
Register-ScheduledTask -TaskName DbTools -Action $a -Principal $p -Settings $s -Force | Out-Null
"Done: the DbTools task looks into $work"
