# Stand without the launcher (12.11): writes Mods/<mod>/server_settings.ini the same way as the launcher (profile.rs server_settings_ini),
# from [client.<mod>.<section>] of seasons/base.toml with the season on top.
#   python -I tools/stand/server_settings.py <Win64\ue4ss\Mods folder> [season]      (default season — playtest)
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "seasons"


def client(path: Path) -> dict:
    if not path.is_file():
        return {}
    return tomllib.loads(path.read_text(encoding="utf-8-sig")).get("client", {})


def merge(base: dict, over: dict) -> dict:
    out = dict(base)
    for k, v in over.items():
        out[k] = merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


def ini(server_id: str, sections: dict) -> str | None:
    ok = lambda s: s and all(c.isascii() and (c.isalnum() or c == "_") for c in s)
    out = f"; generated by the launcher from the settings of server {server_id}; rewritten on every start\r\n"
    any_ = False
    for sec, vals in sections.items():
        if not isinstance(vals, dict) or not ok(sec):
            continue
        out += f"\r\n[{sec}]\r\n"
        for k, v in vals.items():
            if not ok(k) or isinstance(v, (dict, list)):
                continue
            v = ("1" if v else "0") if isinstance(v, bool) else str(v).replace("\r", " ").replace("\n", " ")
            out += f"{k} = {v}\r\n"
            any_ = True
    return out if any_ else None


def main() -> None:
    mods = Path(sys.argv[1])
    season = sys.argv[2] if len(sys.argv) > 2 else "playtest"
    cs = merge(client(ROOT / "base.toml"), client(ROOT / season / "season.toml"))
    for mod, sections in cs.items():
        d = mods / mod
        text = ini("stand", sections) if isinstance(sections, dict) else None
        if not d.is_dir() or not text:
            print(f"{mod}: skipped (no folder or settings)")
            continue
        (d / "server_settings.ini").write_bytes(text.encode("utf-8"))
        print(f"{d / 'server_settings.ini'}: {', '.join(sections)}")


if __name__ == "__main__":
    main()
