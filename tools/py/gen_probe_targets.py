"""Targets for the ClientProbe mod from the UE4SS CXXHeaderDump: event classes (subclasses of UTGFEventArgs), window arguments
(UTGFWindowArgs) and services (UTGFService + helper classes) with paths /Script/<Module>.<Class>.
  python -I tools/gen_probe_targets.py      (from the backups root) → ue4ss/Mods/ClientProbe/Scripts/targets.lua
"""
import sys as _sys, pathlib as _pl; _sys.path.insert(0, str(_pl.Path(__file__).resolve().parent))
from wspaths import ROOT, W  # noqa: E402  workspace paths (docs/WORKSPACE_PLAN.md)
import glob
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")
DUMP = str(W("ue4ss/CXXHeaderDump"))
OUT = str(W("ue4ss/Mods/ClientProbe/Scripts/targets.lua"))

parent, module = {}, {}
fields = {}
for f in glob.glob(os.path.join(DUMP, "*.hpp")):
    mod = os.path.basename(f)[:-4]
    if mod.endswith("_enums"):
        continue
    text = open(f, encoding="utf-8", errors="replace").read()
    for m in re.finditer(r"^class (U\w+) : public (U\w+)\n\{(.*?)^\}; // Size", text, re.M | re.S):
        cls, base, body = m.groups()
        parent[cls], module[cls] = base, mod
        fields[cls] = re.findall(r"^    [\w:<>*, ]+?\s\*?(\w+);\s+// 0x", body, re.M)


def derives(cls, root):
    seen = set()
    while cls in parent and cls not in seen:
        seen.add(cls)
        cls = parent[cls]
        if cls == root:
            return True
    return False


def path(cls):
    return f"/Script/{module[cls]}.{cls[1:]}"


events = sorted(c for c in parent if derives(c, "UTGFEventArgs"))
windows = sorted(c for c in parent if derives(c, "UTGFWindowArgs"))
services = sorted(c for c in parent if derives(c, "UTGFService"))
# Not services, but we hook their functions too: protocol errors, login, windows, toasts/alerts
EXTRA = ["UTGFNetworkFunctionLibrary", "UTGFNetworkManager", "UTGFWindowManager", "UToastWindow", "UAlertWindow",
         "UAsyncAction_ShowAlert", "UAsyncAction_ShowConfirm"]
services += [c for c in EXTRA if c in parent and c not in services]

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8", newline="\n") as w:
    w.write("-- Generated by tools/gen_probe_targets.py from ue4ss/CXXHeaderDump — do not edit by hand.\n")
    w.write("-- events: subclasses of UTGFEventArgs (fields are dumped when the object is created), services: subclasses of UTGFService.\n")
    w.write("return {\n    events = {\n")
    for c in events:
        w.write(f'        "{path(c)}",\n')
    w.write("    },\n    windows = {\n")
    for c in windows:
        w.write(f'        "{path(c)}",\n')
    w.write("    },\n    services = {\n")
    for c in services:
        w.write(f'        "{path(c)}",\n')
    w.write("    },\n}\n")
print(f"events {len(events)}, windows {len(windows)}, classes with functions {len(services)} → {OUT}")

# Lua probe in the pak: proto wrappers of responses (UTGFProto*) — for them we catch field reads from the client's Lua
LUA_OUT = "debug/luaprobe/zzzzzzzz_LuaProbe_P/Dungeonborne/Content/Script/Game/System/Match/LuaProbeTargets.lua"
protos = sorted(c for c in parent if c.startswith("UTGFProtoTgf") and module.get(c) == "TGFBattleProtocol")
# FTGF* structs (TGFGame/TGFBattleProtocol): service data read by the UI (FTGFMailContent etc.)
structs = set()
for mod in ("TGFGame", "TGFBattleProtocol"):
    text = open(os.path.join(DUMP, mod + ".hpp"), encoding="utf-8", errors="replace").read()
    structs |= set(re.findall(r"^struct (FTGF\w+)\n\{", text, re.M))
with open(LUA_OUT, "w", encoding="utf-8", newline="\n") as w:
    w.write("-- Generated by tools/gen_probe_targets.py — do not edit by hand.\n")
    w.write("-- classes: proto wrappers UTGFProtoTgf* (TGFBattleProtocol); structs: FTGF* (TGFGame, TGFBattleProtocol).\n")
    w.write("return {\n  classes = {\n")
    for c in protos:
        w.write(f'    "{c}",\n')
    w.write("  },\n  structs = {\n")
    for c in sorted(structs):
        w.write(f'    "{c}",\n')
    w.write("  },\n}\n")
print(f"proto classes {len(protos)}, structs {len(structs)} → {LUA_OUT}")
with_err = [c for c in events if "ErrorCode" in fields.get(c, [])]
print(f"events with ErrorCode: {len(with_err)}")
