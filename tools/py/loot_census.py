"""Census of loot sources from RuServer logs ([CENSUS] and [LOOT] lines, audit stage 1, 11.11).

    python -I -X utf8 tools/loot_census.py <RuServer log> [more logs…] [--season playtest] [--out loot/census_report.md]

[CENSUS] map=<level> battle=<id> loot=<loot map> total=N: Class=count,…  — accumulated unique sources of the floor
[LOOT] map=<level> loot=<loot map> type=<type> class=<Class> inst=<instance> src=<…>   — a native Loot call

For each match the last [CENSUS] line of each floor is taken; the match's floors are added up. A [LOOT] belongs to the match by
the last [CENSUS] line of the same file before it. Expected loot is computed from the tables (tools/loot_audit.py, the game's formula):
"everything on the map" — if everything is opened/killed, "actual" — by the real Loot calls.
"""
import sys as _sys, pathlib as _pl; _sys.path.insert(0, str(_pl.Path(__file__).resolve().parent))
from wspaths import ROOT, W  # noqa: E402  workspace paths (docs/WORKSPACE_PLAN.md)
import argparse
import collections
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import loot_audit as la  # noqa: E402

CENSUS = re.compile(r"\[CENSUS\] map=(\S+) battle=(\S+) loot=(\d+) total=\d+(?: part=(\d+))?: (.*)$")
# dropped items on the floor (a loot result, not a source): BP_CollectableBase_C — any item, BP_Loot_Gold_* — gold
OUTPUT = re.compile(r"^(BP_CollectableBase_C|BP_Loot_Gold_\d+_C)$")
LOOT = re.compile(r"\[LOOT\] map=(\S+) loot=(\d+) type=(\S+) class=(\S+) inst=(\S+)")


def parse(files):
    battles = {}  # battle -> {"loot": id, "floors": {map: Counter}, "calls": Counter, "types": Counter}
    for f in files:
        cur = None
        for line in Path(f).read_text(encoding="utf-8", errors="replace").splitlines():
            m = CENSUS.search(line)
            if m:
                lvl, bid, loot, part, rest = m.group(1), m.group(2), int(m.group(3)), int(m.group(4) or 1), m.group(5)
                if bid == "nil" or loot == 0:
                    cur = None  # hall before the match assignment — not a match
                    continue
                b = battles.setdefault(bid, {"loot": loot, "floors": {}, "calls": collections.Counter(),
                                             "types": collections.Counter(), "insts": set()})
                b["loot"] = loot or b["loot"]
                # part=1 (or an old line without part) starts a new floor summary, the following parts append to it
                c = collections.Counter() if part == 1 else b["floors"].get(lvl, collections.Counter())
                for kv in rest.split(","):
                    if "=" in kv and not kv.endswith("..."):
                        k, v = kv.rsplit("=", 1)
                        if v.isdigit() and not OUTPUT.match(k):
                            c[k] = int(v)
                if "Matching" not in lvl:  # waiting hall: decor without loot, not counted as a floor
                    b["floors"][lvl] = c
                cur = bid
                continue
            m = LOOT.search(line)
            if m and cur:
                b = battles[cur]
                inst = m.group(5)
                if (m.group(1), inst) in b["insts"] and inst != "?":
                    continue  # the same source repeated
                b["insts"].add((m.group(1), inst))
                b["calls"][m.group(4)] += 1
                b["types"][m.group(3)] += 1
    return battles


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("logs", nargs="+")
    ap.add_argument("--season", default="playtest")
    ap.add_argument("--out", default=str(la.W("loot") / "census_report.md"))
    a = ap.parse_args()
    d = la.Data(a.season or None)
    by_name = {v: k for k, v in d.srcname.items()}
    battles = {k: b for k, b in parse(a.logs).items() if b["floors"]}  # matches where players reached a floor
    if not battles:
        sys.exit("no [CENSUS] lines")

    L = [f"# Census of loot sources ({len(battles)} matches)\n",
         "Generated by `tools/loot_census.py` from RuServer logs. Loot tables — season `" + (a.season or "base") + "`.\n"]
    by_map = collections.defaultdict(list)
    for bid, b in battles.items():
        by_map[b["loot"]].append((bid, b))
    for loot, lst in sorted(by_map.items()):
        L.append(f"## {loot} {la.MAPS.get(loot, '')} — matches {len(lst)}\n")
        total = collections.Counter()
        calls = collections.Counter()
        for _, b in lst:
            for c in b["floors"].values():
                total.update(c)
            calls.update(b["calls"])
        n = len(lst)
        L.append("| Source | class | on the map per match | Loot per match | no loot in the table |")
        L.append("|---|---|---|---|---|")
        unknown = []
        for cls in sorted(set(total) | set(calls), key=lambda k: -total.get(k, 0)):
            sid = by_name.get(cls)
            no_row = sid is None or d.expect(sid, loot) is None
            if sid is None:
                unknown.append(cls)
            L.append(f"| {cls} | {la.source_class(cls)} | {la.fmt(total[cls] / n, 1)} | {la.fmt(calls[cls] / n, 1)} | "
                     f"{'yes' if no_row else ''} |")
        L.append("")
        for title, cnt in (("open/kill everything on the map", total), ("actual (Loot calls)", calls)):
            agg = collections.Counter()
            for cls, k in cnt.items():
                sid = by_name.get(cls)
                e = d.expect(sid, loot) if sid is not None else None
                if e:
                    for key, v in e.items():
                        agg[key] += v * k / n
            items = sum(v for k, v in agg.items() if not k.startswith("eq:") and k not in ("gold", "value"))
            L.append(f"**Expected per match, {title}:** items {la.fmt(items, 1)}, gold {la.fmt(agg['gold'], 0)}, "
                     f"value of the rest {la.fmt(agg['value'], 0)}; equipment: "
                     + ", ".join(f"{la.RARITY_RU[r]} {la.fmt(agg.get('eq:' + r, 0), 2)}" for r in la.RARITY) + "\n")
        if unknown:
            L.append("Classes not from loot_source_map (they have no loot): " + ", ".join(unknown) + "\n")
        types = collections.Counter()
        for _, b in lst:
            types.update(b["types"])
        L.append("Loot types in calls: " + ", ".join(f"{t}: {c}" for t, c in types.most_common()) + "\n")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{a.out}: matches {len(battles)}, maps {len(by_map)}")


if __name__ == "__main__":
    main()
